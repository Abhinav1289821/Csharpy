/// <summary>What durable evidence lets us decide, after a crash, whether a write committed.</summary>
public sealed record WriteEvidence(string Kind, long DocumentId, int? ExpectedModifyCnt = null, string? Reference = null)
{
    public const string Create = "create", Amend = "amend", Delete = "delete";

    /// <summary>A voucher correction: HQ keeps ModifyCnt at 0 for vouchers, but re-inserts every ledger row, and identity
    /// values only grow. So "all of the voucher's ledger rows are newer than <see cref="AfterEntry"/>" proves the commit.</summary>
    public const string VoucherAmend = "voucher-amend";

    /// <summary>Master writes. A created item/account is proven by its row (identity values are never reused). A change is
    /// proven by a row HQ's save always re-inserts: the item's unit row, or account 5's opening-difference row.</summary>
    public const string ItemCreate = "item-create", ItemUpdate = "item-update", AccountCreate = "account-create", AccountUpdate = "account-update";

    public long? AfterEntry { get; init; }

    /// <summary>For an account change: the account's content before and after the write.</summary>
    public string? Fingerprint { get; init; }
    public string? PreviousFingerprint { get; init; }

    public const string AccountFingerprintSql = """
        SELECT CONVERT(varchar(64), HASHBYTES('SHA2_256', (SELECT a.Act_Name, a.Act_Type, a.Rec_Higher, a.Act_OPbal, a.Act_OpSign, a.Act_Usage, a.Act_BillMode,
            d.person, d.Add_Line1, d.Add_Line2, d.Act_Town, d.Act_District, d.Act_state, d.Act_PinNo, d.Act_Ph1, d.Act_Cell, d.Act_Email, d.GSTIN, d.GSTTaxType, d.Act_PAN
          FROM dbo.IQAccmst a LEFT JOIN dbo.IQAccAdr d ON d.Act_Id=a.Act_Id WHERE a.Act_Id=@id FOR XML RAW)), 2)
        """;
}

/// <summary>A plan prepared inside the write transaction from fresh HQ data.</summary>
public sealed record PreparedWrite<TResult>(WritePlan Plan, Func<PlanOutcome, (TResult Result, WriteEvidence Evidence)> Complete);

public sealed record WriteRequest<TResult>(
    HqFirm Firm,
    string OperationId,
    string Kind,
    string RequestHash,
    IReadOnlyList<long> HqDocumentLocks,
    Func<HqSession, Task<PreparedWrite<TResult>>> Prepare);

/// <summary>
/// The only path by which anything is written to HQ. Layers, outermost first:
/// <list type="number">
/// <item>in-process keyed lock and a Windows file lease on the operation id (two clicks, two tabs, two
/// processes on this PC can never run the same operation twice);</item>
/// <item>the SQLite journal: a committed id returns its stored receipt; an interrupted one is settled by
/// probing HQ before anything is retried;</item>
/// <item>HQ's own .HQS edit locks for documents being changed;</item>
/// <item>one SERIALIZABLE transaction, SQL application locks shared by every MK terminal on the LAN, the plan,
/// and its verification steps;</item>
/// <item>evidence written durably before COMMIT, so an unknown commit outcome is never guessed.</item>
/// </list>
/// Transient conflicts (a number taken by an HQ PC a millisecond earlier, a deadlock with HQ) roll back
/// completely and re-plan from fresh data, up to five times.
/// </summary>
public sealed class WriteCoordinator(
    EngineStore store,
    PlanExecutor executor,
    HqOptions options,
    HqContract contract,
    ILogger<WriteCoordinator> log)
{
    private readonly KeyedAsyncLock _inProcess = new();
    private static readonly JsonSerializerOptions Json = new(JsonSerializerDefaults.Web);
    private string LeaseDirectory => Path.Combine(options.DataDirectory, "leases");

    public async Task<TResult> RunAsync<TResult>(WriteRequest<TResult> request, CancellationToken ct = default)
    {
        Guard.Require(Guid.TryParse(request.OperationId, out _), "INVALID_OPERATION_ID", "Operation id must be a GUID generated by the client");
        contract.RequireWritable(request.Firm);
        var key = $"{request.Firm.Id}:{request.OperationId}";
        var timeout = TimeSpan.FromSeconds(options.LockTimeoutSeconds);

        await using var local = await _inProcess.AcquireAsync("op:" + key, timeout, ct);
        await using var lease = await FileLease.AcquireAsync(LeaseDirectory, "op:" + key, timeout, ct);

        var record = store.BeginOperation(request.OperationId, request.Firm.Id, request.Kind, request.RequestHash);
        Guard.Require(record.Firm == request.Firm.Id && record.Kind == request.Kind && record.RequestHash == request.RequestHash,
            "OPERATION_ID_REUSED", "This operation id was already used for a different request", FailureKind.Conflict);

        if (record.Status == OperationStatus.Committed)
            return JsonSerializer.Deserialize<TResult>(record.Result!, Json)!;
        if (record.Status is OperationStatus.Committing or OperationStatus.Uncertain)
        {
            var settled = await SettleAsync(request.Firm, record, ct);
            if (settled == true)
            {
                if (record.Result is not null) return JsonSerializer.Deserialize<TResult>(record.Result, Json)!;
                throw new HqException("HQ_COMMITTED_RECEIPT_MISSING", "This save reached HQ earlier; open the document in HQ or MK to see it.", FailureKind.Conflict,
                    new { documentId = record.DocumentId });
            }
            if (settled is null)
                throw new HqException("HQ_COMMIT_UNCERTAIN", "An earlier attempt may have saved this document. Check HQ before trying again.", FailureKind.Uncertain,
                    new { documentId = record.DocumentId });
            store.Update(record.Id, OperationStatus.Pending);
        }

        await using var documentLock = HqDocumentLock.Acquire(options.HqServerPath, options.RequireHqDocumentLocks, request.Firm.Database, request.HqDocumentLocks);

        for (var attempt = 1; ; attempt++)
        {
            try
            {
                return await AttemptAsync(request, ct);
            }
            catch (HqException e) when (attempt < 5 && e.Code is "HQ_NUMBER_TAKEN" or "HQ_DEADLOCK" or "HQ_BUSY")
            {
                log.LogWarning("Retrying {Kind} {Operation} after {Code} (attempt {Attempt})", request.Kind, request.OperationId, e.Code, attempt);
                await Task.Delay(TimeSpan.FromMilliseconds(40 * attempt * attempt), ct);
            }
            catch (HqException e) when (e.Kind != FailureKind.Uncertain)
            {
                store.Update(request.OperationId, OperationStatus.Rejected, errorCode: e.Code, errorMessage: e.Message);
                throw;
            }
        }
    }

    private async Task<TResult> AttemptAsync<TResult>(WriteRequest<TResult> request, CancellationToken ct)
    {
        await using var session = await request.Firm.OpenAsync(ct);
        await session.BeginAsync(IsolationLevel.Serializable);
        // One MK writer per firm database at a time, across every terminal on the LAN, taken before the first read:
        // two MK writers can then never hold serializable read locks the other needs. HQ itself never waits on this.
        await session.AppLockAsync($"MK:write:{request.Firm.Database}", options.LockTimeoutSeconds * 1000);
        await session.AppLockAsync($"MK:op:{request.Firm.Database}:{request.OperationId}", options.LockTimeoutSeconds * 1000);
        foreach (var doc in request.HqDocumentLocks.Distinct().Order())
            await session.AppLockAsync($"MK:doc:{request.Firm.Database}:{doc}", options.LockTimeoutSeconds * 1000);

        var prepared = await request.Prepare(session);
        var outcome = await executor.ExecuteAsync(session, prepared.Plan, options.LockTimeoutSeconds * 1000, ct);
        var (result, evidence) = prepared.Complete(outcome);
        var resultJson = JsonSerializer.Serialize(result, Json);

        // Durable evidence first; only then COMMIT.
        store.Update(request.OperationId, OperationStatus.Committing, evidence.DocumentId, JsonSerializer.Serialize(evidence, Json), resultJson);
        try
        {
            await session.CommitAsync(outcome.FinalChecks);
        }
        catch (HqException e) when (e.Code == "HQ_NUMBER_TAKEN")
        {
            // Not committed: the batch raised before COMMIT. Roll back and let RunAsync re-plan with a fresh number.
            await session.RollbackAsync();
            throw;
        }
        catch (Exception e) when (e is not OperationCanceledException)
        {
            log.LogError(e, "COMMIT outcome unknown for {Operation}", request.OperationId);
            store.Update(request.OperationId, OperationStatus.Uncertain, errorCode: "HQ_COMMIT_UNCERTAIN", errorMessage: e.Message);
            var settled = await SettleAsync(request.Firm, store.GetOperation(request.OperationId)!, ct);
            if (settled == true)
            {
                store.Update(request.OperationId, OperationStatus.Committed);
                return result;
            }
            if (settled == false)
            {
                store.Update(request.OperationId, OperationStatus.Rejected, errorCode: "HQ_COMMIT_FAILED", errorMessage: e.Message);
                throw new HqException("HQ_COMMIT_FAILED", "SQL Server did not save the document; nothing was written. Try again.", FailureKind.Unavailable, inner: e);
            }
            throw new HqException("HQ_COMMIT_UNCERTAIN", "The connection dropped while saving. MK will confirm with HQ before any retry.", FailureKind.Uncertain, inner: e);
        }
        store.Update(request.OperationId, OperationStatus.Committed);
        return result;
    }

    /// <summary>true = committed, false = definitely not committed, null = cannot tell yet.</summary>
    public async Task<bool?> SettleAsync(HqFirm firm, OperationRecord record, CancellationToken ct = default)
    {
        if (record.Evidence is null) return false; // evidence is written before COMMIT; without it nothing committed
        var evidence = JsonSerializer.Deserialize<WriteEvidence>(record.Evidence, Json)!;
        try
        {
            await using var s = await firm.OpenAsync(ct);
            var header = await s.QueryFirstOrDefaultAsync<(long DocId, int ModifyCnt)?>(
                "SELECT CAST(Doc_Id AS bigint), CAST(ISNULL(ModifyCnt,0) AS int) FROM dbo.IQDoc_Header WHERE Doc_Id=@id", new { id = evidence.DocumentId });
            bool? verdict = evidence.Kind switch
            {
                WriteEvidence.ItemCreate => await s.ScalarAsync<int>("SELECT COUNT(*) FROM dbo.IQItems_Mast WHERE Item_ID=@id", new { id = evidence.DocumentId }) > 0,
                WriteEvidence.ItemUpdate => await s.ScalarAsync<long>("SELECT ISNULL(MAX(ItemUnitsDtldID),0) FROM dbo.IQItems_Units WHERE Item_ID=@id AND Recd_ID=0", new { id = evidence.DocumentId }) > evidence.AfterEntry,
                WriteEvidence.AccountCreate => await s.ScalarAsync<int>("SELECT COUNT(*) FROM dbo.IQAccmst WHERE Act_Id=@id", new { id = evidence.DocumentId }) > 0,
                WriteEvidence.AccountUpdate => await s.ScalarAsync<string?>(WriteEvidence.AccountFingerprintSql, new { id = evidence.DocumentId }) is var now
                    && now == evidence.Fingerprint ? true : now == evidence.PreviousFingerprint ? false : null,
                WriteEvidence.Create when header is not null => true,
                // Identity values are never reused: an audited-but-missing document was saved and later deleted in HQ.
                WriteEvidence.Create => await s.ScalarAsync<int>("SELECT COUNT(*) FROM dbo.User_IQDOC_Header WHERE Doc_Id=@id", new { id = evidence.DocumentId }) > 0,
                WriteEvidence.Delete => header is null,
                WriteEvidence.VoucherAmend when header is null => null,
                WriteEvidence.VoucherAmend => await s.ScalarAsync<long>("SELECT ISNULL(MIN(SR_NO),0) FROM dbo.IQDayBook WHERE Doc_ID=@id", new { id = evidence.DocumentId }) > evidence.AfterEntry,
                WriteEvidence.Amend when header is null => null,
                WriteEvidence.Amend when header.Value.ModifyCnt == evidence.ExpectedModifyCnt => true,
                WriteEvidence.Amend when header.Value.ModifyCnt == evidence.ExpectedModifyCnt - 1 => false,
                _ => null,
            };
            if (verdict == true) store.Update(record.Id, OperationStatus.Committed);
            if (verdict == false) store.Update(record.Id, OperationStatus.Rejected, errorCode: "HQ_NOT_COMMITTED", errorMessage: "Settled after an interrupted save: not in HQ");
            return verdict;
        }
        catch (HqException e) when (e.Kind == FailureKind.Unavailable)
        {
            return null;
        }
    }

    /// <summary>Run at startup: settle every journal entry an earlier crash left open.</summary>
    public async Task<int> RecoverAsync(FirmRegistry firms, CancellationToken ct = default)
    {
        var settled = 0;
        foreach (var record in store.Operations(null, 500, unsettledOnly: true))
        {
            var firm = firms.All.FirstOrDefault(f => f.Id == record.Firm);
            if (firm is null) continue;
            var verdict = await SettleAsync(firm, record, ct);
            if (verdict is not null) settled++;
            log.LogInformation("Recovery: operation {Id} ({Kind}) settled as {Verdict}", record.Id, record.Kind, verdict?.ToString() ?? "unknown");
        }
        return settled;
    }
}
